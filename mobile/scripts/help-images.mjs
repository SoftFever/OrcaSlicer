#!/usr/bin/env node
// Generates apps/orca/lib/help/images.ts: a map from help image key
// ("<topic>/<file>") to a static require() of the PNG under apps/orca/assets/help,
// so Metro bundles every screenshot the guides use. Run with `pnpm help-images`
// from mobile/ after adding or replacing screenshots; help-docs runs it too.

import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const app = resolve(here, '..', 'apps', 'orca')
const assets = join(app, 'assets', 'help')
const out = join(app, 'lib', 'help', 'images.ts')

function* pngs(dir) {
  if (!existsSync(dir)) return
  for (const entry of readdirSync(dir).sort()) {
    const path = join(dir, entry)
    if (statSync(path).isDirectory()) yield* pngs(path)
    else if (/\.png$/i.test(entry)) yield path
  }
}

const entries = []
for (const file of pngs(assets)) {
  const key = relative(assets, file)
    .replace(/\\/g, '/')
    .replace(/\.png$/i, '')
  const req = '../../assets/help/' + relative(assets, file).replace(/\\/g, '/')
  entries.push(`  '${key}': require('${req}') as number,`)
}

const text = [
  '// Generated by mobile/scripts/help-images.mjs; do not edit. Keys are',
  '// "<topic>/<file>" under assets/help, values are Metro asset ids.',
  'export const helpImages: Record<string, number> = {',
  ...entries,
  '}',
  '',
].join('\n')

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, text)
console.log(`help-images: ${entries.length} image(s) -> ${relative(process.cwd(), out)}`)
